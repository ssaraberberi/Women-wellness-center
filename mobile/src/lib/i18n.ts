export type TKey = keyof typeof dict;

export function translate(lang: 'sq' | 'en', key: TKey, vars?: Record<string, string | number>) {
  let s = dict[key]?.[lang === 'sq' ? 0 : 1] ?? String(key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** For enum values from the API (statuses, types): translated if known, shown as-is otherwise. */
export function tEnum(lang: 'sq' | 'en', value: string) {
  return value in dict ? translate(lang, value as TKey) : value;
}

export function useT() {
  const lang = useAuth((s) => s.lang);
  const t = (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
  return { t, lang, tEnum: (v: string) => tEnum(lang, v) };
}

